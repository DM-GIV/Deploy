const MIN_RE = new RegExp(`(?<![а-я])(?:от|не\\s+(?:менее|дешевле|ниже|меньше)|дороже|более|свыше|минимум|больше)\\s*${NUM}${UNIT_RE}`, 'g');
const MONTH_ALT = MONTHS.join('|');
const DEADLINE_TO_RE = new RegExp(`(?<![а-я])до\\s+(\\d{1,2})\\s+(${MONTH_ALT})(?:\\s+(\\d{4}))?(?:\\s+года?)?`);
const SOON_RE = /(?<![а-я])в\s+ближайш[а-я]*\s+(\d{1,3})?\s*(дн[а-я]*|недел[а-я]*|месяц[а-я]*)/;

function isoDate(date) { return date.toISOString().slice(0, 10); }
function consume(text, regexp) { return text.replace(regexp, ' '); }

export function parseIntent(rawQuery, { now = new Date() } = {}) {
  let text = ` ${normalizeIntentText(rawQuery)} `;
  const filters = { limit: 5 };
  const interpretation = [];
  const notes = [];
  const clarifications = [];
  const add = (label, value) => interpretation.push({ label, value });

  // --- deadline (before prices: "до 30 ноября" must not be read as a price) --------------------------------
  let m = text.match(DEADLINE_TO_RE);
  if (m) {
    const month = MONTHS.indexOf(m[2]);
    let year = m[3] ? Number(m[3]) : now.getUTCFullYear();
    let end = new Date(Date.UTC(year, month, Number(m[1])));
    if (!m[3] && end < new Date(now.getTime() - 86400000)) { year += 1; end = new Date(Date.UTC(year, month, Number(m[1]))); }
    if (Number(m[1]) < 1 || Number(m[1]) > 31 || end.getUTCMonth() !== month) clarifications.push('Не удалось разобрать дату окончания приёма заявок. Укажите её в формате «до 30 ноября».');
    else {
      filters.deadline_from = isoDate(now);
      filters.deadline_to = isoDate(new Date(end.getTime() + 86400000));
      add('Приём заявок', `до ${m[1]} ${m[2]}${m[3] ? ' ' + m[3] : ''} включительно`);
    }
    text = consume(text, DEADLINE_TO_RE);
  } else if ((m = text.match(SOON_RE))) {
    const n = m[1] ? Number(m[1]) : 1;
    const days = m[2].startsWith('дн') ? n : m[2].startsWith('недел') ? n * 7 : n * 30;
    if (days >= 1 && days <= 120) {
      filters.deadline_from = isoDate(now);
      filters.deadline_to = isoDate(new Date(now.getTime() + (days + 1) * 86400000));
      add('Приём заявок', `заканчивается в ближайшие ${days} дн.`);
    } else clarifications.push('Срок «в ближайшие …» слишком велик. Укажите период до 120 дней.');
    text = consume(text, SOON_RE);
  }

  // --- price --------------------------------------------------------------------------------------------------
  const prices = { min: null, max: null };
  for (const match of text.matchAll(MIN_RE)) { const v = money(match[1], match[2]); if (v != null) prices.min = prices.min == null ? v : Math.max(prices.min, v); }
  for (const match of text.matchAll(MAX_RE)) { const v = money(match[1], match[2]); if (v != null) prices.max = prices.max == null ? v : Math.min(prices.max, v); }
  text = text.replace(MIN_RE, ' ').replace(MAX_RE, ' ').replace(/(?<![а-я])(?:руб(?:л[а-я]*)?|₽|р)(?![а-я])\.?/g, ' ');
  if (prices.min != null && prices.max != null && prices.min > prices.max) {
    clarifications.push('Нижняя граница цены больше верхней. Уточните диапазон.');
  } else {
    if (prices.min != null) { filters.price_min = prices.min; }
    if (prices.max != null) { filters.price_max = prices.max; }
    const fmt = v => new Intl.NumberFormat('ru-RU').format(v);
    if (prices.min != null || prices.max != null) add('Цена', prices.min != null && prices.max != null ? `${fmt(prices.min)} – ${fmt(prices.max)} ₽` : prices.max != null ? `до ${fmt(prices.max)} ₽` : `от ${fmt(prices.min)} ₽`);
  }

  // --- procedure -----------------------------------------------------------------------------------------------
  const procedures = [];
  for (const [code, label, regexp] of PROCEDURE_RULES) {
    if (regexp.test(text)) { procedures.push(code); text = consume(text, regexp); add('Процедура', label); }
  }
  if (procedures.length) filters.procedures = procedures;

  // --- geography -----------------------------------------------------------------------------------------------
  const districts = new Set();
  for (const [name, regexp] of FD_PATTERNS) {
    if (regexp.test(text)) { districts.add(name); text = consume(text, regexp); }
  }
  const regions = new Set();
  let povolzhye = false;
  if (/(?<![а-я])(?:поволжь[а-я]*|в\s+поволжье)/.test(text)) {
    povolzhye = true; POVOLZHYE.forEach(r => regions.add(r)); text = text.replace(/(?<![а-я])поволжь[а-я]*/g, ' ');
    notes.push(`«Поволжье» понимается как Волжский экономический район: ${POVOLZHYE.join(', ')}. Это не весь Приволжский федеральный округ.`);
  }
  const viaCity = [];
  for (const [name, patterns] of REGION_PATTERNS) {
    for (const pattern of patterns) {
      const hit = text.match(pattern);
      if (!hit) continue;
      regions.add(name);
      if (CITY_ONLY.has(hit[0].replace(/[аеыуой]$/, '')) || /^(казан|самар|уф|екатеринбург|владивосток|сургут|ижевск|чебоксар|питер|столиц)/.test(hit[0])) viaCity.push([hit[0], name]);
      text = consume(text, pattern);
      break;
    }
  }
  if (!povolzhye && (/(?<![а-я])федеральн/.test(text))) clarifications.push('Не удалось определить федеральный округ. Назовите его целиком (например, «Южный федеральный округ») или аббревиатурой (ЮФО).');
  const unresolved = text.match(UNRESOLVED_GEO);
  if (unresolved) clarifications.push(`Название «${unresolved[0].trim()}» не соответствует точному региону. Укажите субъект РФ или федеральный округ (например, «Сибирский федеральный округ»).`);
  else if (!regions.size && !districts.size && GEO_MARKER.test(text) && /(?<![а-я])(?:в|во|по)\s+[а-я-]+(?:\s+[а-я-]+)?\s*(?:област|кра[йяеюём]|республик|округ|район)/.test(text)) {
    clarifications.push('Не удалось определить регион по названию. Укажите субъект РФ точнее (например, «в Самарской области»).');
  }
  if (districts.size) { filters.federal_districts = [...districts]; add('Федеральный округ', [...districts].join(', ')); }
  if (regions.size && !povolzhye) { filters.regions = [...regions]; add('Регион', [...regions].join(', ')); }
  else if (povolzhye) { filters.regions = [...regions]; add('Поволжье (Волжский экономический район)', POVOLZHYE.join(', ')); }
  for (const [word, region] of viaCity) notes.push(`Город «${word.trim()}» → регион «${region}». Сужение до города не выполняется: поиск идёт по региону.`);
  if (districts.size && regions.size && !povolzhye) {
    notes.push('Указаны и регион, и федеральный округ: оба условия применяются одновременно (лот должен подходить под оба).');
  }

  // --- property type ---------------------------------------------------------------------------------------------
  const subtypes = new Set();
  const classes = new Set();
  const labels = [];
  const keywords = [];
  for (const rule of TYPE_RULES) {
    for (const pattern of rule.patterns) {
      const hit = text.match(pattern);
      if (!hit) continue;
      rule.subtypes.forEach(s => subtypes.add(s));
      (rule.classes || []).forEach(c => classes.add(c));
      labels.push(rule.label);
      if (rule.trailer) {
        const qualifier = (hit[1] || hit[3] || '').trim();
        const prefix = hit[2] || '';
        const word = (hit[0].match(/(авто|полу)?прицеп[а-я]*/) || [''])[0];
        if (prefix === 'полу' || /^полуприцеп/.test(word)) { keywords.push('полуприцеп'); notes.push('«Полуприцеп» ищется как отдельный тип: в названии лота должно быть слово «полуприцеп».'); }
        if (qualifier.startsWith('легков')) { keywords.push('легковой'); notes.push('«Прицеп легковой»: в названии лота должно быть слово «легковой».'); }
        if (qualifier.startsWith('грузов')) { keywords.push('грузовой'); notes.push('«Прицеп грузовой»: в названии лота должно быть слово «грузовой».'); }
        if (!keywords.length && /(?<![а-я])прицеп/.test(word)) notes.push('«Прицеп» без уточнения включает прицепы и полуприцепы всех видов.');
      }
      text = consume(text, pattern);
      break;
    }
  }
  if (subtypes.size) { filters.asset_subtypes = [...subtypes]; add('Тип имущества', labels.join(', ')); }
  if (classes.size && !subtypes.size) { filters.asset_classes = [...classes]; add('Тип имущества', labels.join(', ')); }
  if (classes.size && subtypes.size) { /* a broad class together with a precise subtype: the subtype is the stricter AND condition */ }
  if (keywords.length) filters.keywords = [...new Set(keywords)];

  // --- unsupported constraints -------------------------------------------------------------------------------
  if (/(?<![а-я])(?:заверш[а-я]*|прошедш[а-я]*|состоявш[а-я]*|архив[а-я]*|итоги|результаты\s+торгов)/.test(text)) {
    clarifications.push('Поиск показывает только лоты с приёмом заявок. Завершённые торги и архив не ищутся.');
  }
  const leftover = text.replace(/[.,/()\-]+/g, ' ').split(/\s+/).filter(w => w.length >= 4 && !STOP.has(w) && !/^\d+$/.test(w));
  const ignored = [...new Set(leftover)].slice(0, 6);

  const structured = Boolean(filters.asset_subtypes || filters.asset_classes || filters.regions || filters.federal_districts || filters.procedures
    || filters.price_min != null || filters.price_max != null || filters.keywords);
  if (!clarifications.length && !filters.asset_subtypes && !filters.asset_classes) {
    clarifications.push('Не удалось определить тип имущества. Укажите, что вы ищете: например, «квартиры», «земельные участки», «грузовые автомобили», «нежилые помещения».');
  }
  if (!clarifications.length && !structured) clarifications.push('Уточните запрос: тип имущества, регион, цену или вид процедуры.');
  return {
    filters: clarifications.length ? null : filters,
    interpretation,
    notes: [...new Set(notes)],
    ignored,
    clarification: clarifications.length ? clarifications[0] : null,
    clarifications
  };
}
