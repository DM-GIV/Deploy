export function normalizeIntentText(raw) {
  return String(raw || '').toLowerCase().replace(/ё/g, 'е').replace(/[«»"“”„]/g, ' ').replace(/[^\p{L}\p{N}\s.,\-—–/()]/gu, ' ').replace(/[—–]/g, '-').replace(/\s+/g, ' ').trim();
}

const UNIT = { 'тыс': 1e3, 'т': 1e3, 'к': 1e3, 'млн': 1e6, 'м': 1e6, 'млрд': 1e9 };
function money(numberText, unitText) {
  const clean = numberText.replace(/[\s ]/g, '').replace(',', '.');
  const base = Number(clean);
  if (!Number.isFinite(base)) return null;
  let mult = 1;
  if (unitText) {
    const u = unitText.toLowerCase();
    mult = u.startsWith('тыс') ? 1e3 : u.startsWith('миллиард') || u.startsWith('млрд') ? 1e9 : u.startsWith('миллион') || u.startsWith('млн') ? 1e6 : (UNIT[u.replace(/\./g, '')] || 1);
  }
  const value = Math.round(base * mult);
  return value >= 0 && value <= 1e12 ? value : null;
}
